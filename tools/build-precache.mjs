// Writes precache.js (every file WordSteps needs offline) and js/version.js
// (a hash of them all, shown on the home screen). Run after changing any file:
//   node tools/build-precache.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const shell = [
  './', 'index.html', 'manifest.webmanifest', 'css/app.css',
  ...readdirSync('js').filter((f) => f.endsWith('.js')).sort().map((f) => 'js/' + f),
  'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png',
];
const media = ['pics', 'voice', 'ai'].filter((d) => existsSync('media/' + d)).flatMap((d) => readdirSync('media/' + d).sort().map((f) => `media/${d}/${f}`));
const files = [...shell, ...media];

const hash = createHash('sha256');
hash.update(readFileSync('sw.js'));
for (const f of files) if (f !== './' && f !== 'js/version.js') hash.update(readFileSync(f));
const version = hash.digest('hex').slice(0, 10);

const built = new Date().toLocaleString('en-GB', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit', timeZone: 'Europe/London' });
writeFileSync('js/version.js', `// Generated by tools/build-precache.mjs — do not edit.\nexport const VERSION = '${version}';\nexport const BUILT = '${built}';\n`);
writeFileSync('precache.js', `// Generated by tools/build-precache.mjs — do not edit.\nself.CACHE_VERSION = '${version}';\nself.PRECACHE = ${JSON.stringify(files, null, 0).replace(/","/g, '",\n  "')};\n`);
console.log(`precache.js: ${files.length} files, version ${version}`);
